const crypto = require("crypto");
const cloudinary = require("cloudinary").v2;
const AppError = require("../../util/AppError");

const REQUIRED_ENV_VARS = [
  "CLOUDINARY_CLOUD_NAME",
  "CLOUDINARY_API_KEY",
  "CLOUDINARY_API_SECRET",
];

const UPLOAD_TIMEOUT_MS = 30 * 1000;

let configuredSignature = "";

const readConfig = () => {
  const values = {
    cloud_name: process.env.CLOUDINARY_CLOUD_NAME || "",
    api_key: process.env.CLOUDINARY_API_KEY || "",
    api_secret: process.env.CLOUDINARY_API_SECRET || "",
  };

  const missing = REQUIRED_ENV_VARS.filter((name) => !process.env[name]);
  if (missing.length) {
    throw new AppError(
      `Image storage is not configured. Missing environment variable(s): ${missing.join(", ")}.`,
      503,
    );
  }

  return values;
};

const ensureConfigured = () => {
  const config = readConfig();
  const signature = `${config.cloud_name}|${config.api_key}|${config.api_secret}`;

  if (signature !== configuredSignature) {
    cloudinary.config({ ...config, secure: true });
    configuredSignature = signature;
  }

  return config;
};

const uploadBuffer = (buffer, { folder, mimetype } = {}) => {
  ensureConfigured();

  if (!Buffer.isBuffer(buffer) || buffer.length === 0) {
    throw new AppError("Uploaded image is empty", 400);
  }

  if (!folder) {
    throw new AppError("Image storage folder is required", 500);
  }

  // The public_id is generated by the server. The original client filename is
  // intentionally ignored so it can never influence the storage path.
  const generatedPublicId = crypto.randomUUID();

  return new Promise((resolve, reject) => {
    let settled = false;

    const finish = (error, result) => {
      if (settled) return;
      settled = true;

      if (error) {
        console.error("[cloudinary] upload failed", {
          providerCode: error.name || null,
          httpCode: error.http_code || null,
        });
        const uploadError = new AppError(
          "Image upload failed. Please try again later.",
          502,
        );
        uploadError.cause = error;
        reject(uploadError);
        return;
      }

      if (!result?.secure_url || !result?.public_id) {
        reject(
          new AppError(
            "Image upload failed. The storage provider returned an invalid response.",
            502,
          ),
        );
        return;
      }

      resolve({
        url: result.secure_url,
        publicId: result.public_id,
        width: result.width || null,
        height: result.height || null,
        format: result.format || null,
      });
    };

    try {
      const stream = cloudinary.uploader.upload_stream(
        {
          folder,
          public_id: generatedPublicId,
          resource_type: "image",
          allowed_formats: ["jpg", "jpeg", "png"],
          use_filename: false,
          unique_filename: false,
          overwrite: false,
          invalidate: true,
          timeout: UPLOAD_TIMEOUT_MS,
        },
        finish,
      );

      stream.on("error", (error) => finish(error));
      stream.end(buffer);
    } catch (error) {
      finish(error);
    }
  });
};

const destroy = async (publicId) => {
  ensureConfigured();

  if (!publicId || typeof publicId !== "string") {
    throw new AppError("Cloudinary public_id is required", 500);
  }

  let result;
  try {
    result = await cloudinary.uploader.destroy(publicId, {
      resource_type: "image",
      invalidate: true,
    });
  } catch (error) {
    const storageError = new Error("Cloudinary delete failed");
    storageError.cause = error;
    throw storageError;
  }

  // Cloudinary returns "not found" when the asset has already been removed.
  // Treat that as success so retries are idempotent.
  if (!result || !["ok", "not found"].includes(result.result)) {
    const storageError = new Error("Cloudinary did not confirm asset deletion");
    storageError.result = result?.result;
    throw storageError;
  }

  return result;
};

const resolveUrl = (publicId) => {
  ensureConfigured();

  if (!publicId || typeof publicId !== "string") {
    throw new AppError("Cloudinary public_id is required", 500);
  }

  return cloudinary.url(publicId, {
    secure: true,
    resource_type: "image",
  });
};

const isConfigured = () =>
  REQUIRED_ENV_VARS.every((name) => Boolean(process.env[name]));

module.exports = {
  uploadBuffer,
  destroy,
  resolveUrl,
  isConfigured,
};
